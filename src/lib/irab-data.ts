// Ordered sequence of all verses in Hi I'rab for smooth Prev / Next navigation
export const IRAB_ORDERED_KEYS = [
  "1:1", "1:2", "1:3", "1:4", "1:5", "1:6", "1:7",
  "112:1", "112:2", "112:3", "112:4",
  "113:1", "113:2", "113:3", "113:4", "113:5",
  "114:1", "114:2", "114:3", "114:4", "114:5", "114:6",
];

export function getIrabVersesBySurah(surahId: string): IrabAyatItem[] {
  return IRAB_ORDERED_KEYS
    .map((k) => IRAB_AYAT_DATA[k])
    .filter((item) => item && item.surahId === String(surahId));
}

export function getIrabNavigation(surahId: string, ayat: number | string) {
  const key = `${surahId}:${ayat}`;
  const currentData = IRAB_AYAT_DATA[key] || null;
  const surahVerses = getIrabVersesBySurah(String(surahId));
  const indexInSurah = surahVerses.findIndex((v) => v.key === key);

  const prevInSurah = indexInSurah > 0 ? surahVerses[indexInSurah - 1] : null;
  const nextInSurah =
    indexInSurah >= 0 && indexInSurah < surahVerses.length - 1
      ? surahVerses[indexInSurah + 1]
      : null;

  // Next surah when finishing the last verse of current surah
  const surahIdx = IRAB_SURAH_LIST.findIndex((s) => s.id === String(surahId));
  const prevSurah = surahIdx > 0 ? IRAB_SURAH_LIST[surahIdx - 1] : null;
  const nextSurah =
    surahIdx >= 0 && surahIdx < IRAB_SURAH_LIST.length - 1
      ? IRAB_SURAH_LIST[surahIdx + 1]
      : null;

  const prevSurahLastVerse = prevSurah
    ? getIrabVersesBySurah(prevSurah.id).slice(-1)[0] || null
    : null;
  const nextSurahFirstVerse = nextSurah
    ? getIrabVersesBySurah(nextSurah.id)[0] || null
    : null;

  return {
    currentData,
    surahVerses,
    totalVersesInSurah: surahVerses.length,
    prevInSurah,
    nextInSurah,
    prevGlobal: prevInSurah || prevSurahLastVerse,
    nextGlobal: nextInSurah || nextSurahFirstVerse,
    nextSurah,
    prevSurah,
  };
}

export interface IrabQuizQuestion {
  question: string;
  wordArab?: string;
  correct: string;
  options: string[];
}

const FUNCTION_POOL = [
  "Harf Jar",
  "Majrur / Mudhaf",
  "Mudhaf Ilaih",
  "Na'at",
  "Mubtada'",
  "Khabar",
  "Fi'il Amr",
  "Fi'il Mudhari'",
  "Fi'il Madhi",
  "Maf'ul Bih Muqaddam",
  "Maf'ul Bih Kedua",
  "Badal / Mudhaf",
  "Isim Maushul / Mudhaf Ilaih",
  "Jar Majrur / Khabar",
  "Ma'thuf Majrur",
  "Zharaf Zaman",
  "Harf Nafyi & Jazm",
  "Fi'il Mudhari' Majzum",
];

export function getIrabQuizQuestions(surahId: string, ayat: number | string): IrabQuizQuestion[] {
  const key = `${surahId}:${ayat}`;
  const ayatData = IRAB_AYAT_DATA[key];
  if (!ayatData) return [];

  return ayatData.words.map((w) => {
    const distractors = FUNCTION_POOL.filter((fn) => fn !== w.function);
    // Deterministic shuffle per word so options feel varied but clean
    const picked: string[] = [];
    let seed = (w.word.charCodeAt(0) || 7) + ayatData.ayat * 13;
    while (picked.length < 3 && distractors.length > 0) {
      const idx = seed % distractors.length;
      const candidate = distractors[idx];
      if (!picked.includes(candidate)) {
        picked.push(candidate);
      }
      seed += 7;
    }

    return {
      question: `Apa kedudukan I'rab dari kata « ${w.word} » (${w.trans} — "${w.meaning}")?`,
      wordArab: w.word,
      correct: w.function,
      options: [w.function, ...picked],
    };
  });
}
